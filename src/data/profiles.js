export function toPath(ops) {
  return ops
    .map(([k, ...a]) => {
      if (k === 'A') {
        const [cx, cy, r] = a
        return `L${cx + r} ${cy} A${r} ${r} 0 0 0 ${cx - r} ${cy}`
      }
      if (k === 'Z') return 'Z'
      return `${k}${a.join(' ')}`
    })
    .join(' ')
}
